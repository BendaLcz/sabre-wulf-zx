// Generates crisp ZX Spectrum 48K Sabre Wulf PWA icons (cyan medallion on a jungle backdrop) as PNG, with zero external dependencies: `npm run icons`.
import { mkdirSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { deflateSync } from "node:zlib";
import { JUNGLE_ROWS, JUNGLE_SIZE } from "./jungle-backdrop.mjs";
import { exterior, MED_H, MED_W, medInk, PAD_W } from "./medallion.mjs";

const outDir = join(
  dirname(fileURLToPath(import.meta.url)),
  "..",
  "public",
  "icons",
);
mkdirSync(outDir, { recursive: true });

// ---- Tiny dependency-free PNG encoder ----
const CRC_TABLE = Array.from({ length: 256 }, (_, n) => {
  let c = n;
  for (let k = 0; k < 8; k++) c = c & 1 ? 0xedb88320 ^ (c >>> 1) : c >>> 1;
  return c >>> 0;
});
function crc32(buf) {
  let c = 0xffffffff;
  for (const b of buf) c = CRC_TABLE[(c ^ b) & 0xff] ^ (c >>> 8);
  return (c ^ 0xffffffff) >>> 0;
}
function chunk(type, data) {
  const len = Buffer.alloc(4);
  len.writeUInt32BE(data.length);
  const td = Buffer.concat([Buffer.from(type), data]);
  const crc = Buffer.alloc(4);
  crc.writeUInt32BE(crc32(td));
  return Buffer.concat([len, td, crc]);
}
function encodePng(size, rgb) {
  const ihdr = Buffer.alloc(13);
  ihdr.writeUInt32BE(size, 0);
  ihdr.writeUInt32BE(size, 4);
  ihdr[8] = 8; // 8-bit
  ihdr[9] = 2; // RGB
  const raw = Buffer.alloc((size * 3 + 1) * size);
  for (let y = 0; y < size; y++) {
    raw[y * (size * 3 + 1)] = 0;
    rgb.copy(raw, y * (size * 3 + 1) + 1, y * size * 3, (y + 1) * size * 3);
  }
  return Buffer.concat([
    Buffer.from([0x89, 0x50, 0x4e, 0x47, 0x0d, 0x0a, 0x1a, 0x0a]),
    chunk("IHDR", ihdr),
    chunk("IDAT", deflateSync(raw, { level: 9 })),
    chunk("IEND", Buffer.alloc(0)),
  ]);
}

function buildPixelCanvas() {
  // 128x128 logical grid for every icon: the 96x64 medallion spans 75% of the width, inside Android's 80% maskable safe zone.
  const G = JUNGLE_SIZE;
  const medX = (G - MED_W) / 2;
  const medY = (G - MED_H) / 2;

  const BLACK = [0x00, 0x00, 0x00];
  const ZX_CYAN = [0x00, 0xff, 0xff];

  // Jungle backdrop built from the game's own foliage graphics (scripts/jungle-backdrop.mjs, generated by `npm run jungle`)
  const grid = [];
  for (const row of JUNGLE_ROWS) {
    for (const ch of row) {
      const i = Number(ch);
      grid.push([i & 2 ? 0xff : 0, i & 4 ? 0xff : 0, i & 1 ? 0xff : 0]);
    }
  }

  // Crisp 2px black outer halo around the medallion silhouette so it pops cleanly over the jungle
  for (let my = 0; my < MED_H; my++) {
    for (let mx = 0; mx < MED_W; mx++) {
      if (exterior[(my + 1) * PAD_W + (mx + 1)]) continue;
      for (let hy = -2; hy <= 2; hy++) {
        for (let hx = -2; hx <= 2; hx++) {
          const px = medX + mx + hx;
          const py = medY + my + hy;
          if (px >= 0 && px < G && py >= 0 && py < G) {
            grid[py * G + px] = BLACK;
          }
        }
      }
    }
  }

  // Render the opaque high-detail 96x64 Cyan Sabre Wulf Medallion
  for (let my = 0; my < MED_H; my++) {
    for (let mx = 0; mx < MED_W; mx++) {
      if (exterior[(my + 1) * PAD_W + (mx + 1)]) continue;
      const px = medX + mx;
      const py = medY + my;
      if (px >= 0 && px < G && py >= 0 && py < G) {
        grid[py * G + px] = medInk[my * MED_W + mx] ? ZX_CYAN : BLACK;
      }
    }
  }

  return { grid, G };
}

function renderIcon(size) {
  const { grid, G } = buildPixelCanvas();
  const rgb = Buffer.alloc(size * size * 3);
  for (let y = 0; y < size; y++) {
    const gy = Math.min(G - 1, Math.floor((y * G) / size));
    for (let x = 0; x < size; x++) {
      const gx = Math.min(G - 1, Math.floor((x * G) / size));
      const [r, g, b] = grid[gy * G + gx];
      const idx = (y * size + x) * 3;
      rgb[idx] = r;
      rgb[idx + 1] = g;
      rgb[idx + 2] = b;
    }
  }
  return encodePng(size, rgb);
}

for (const [name, size] of [
  ["icon-192.png", 192],
  ["icon-512.png", 512],
  ["icon-maskable-512.png", 512],
  ["apple-touch-icon.png", 180],
]) {
  writeFileSync(join(outDir, name), renderIcon(size));
  console.log(`wrote public/icons/${name}`);
}
