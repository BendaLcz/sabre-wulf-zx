// Regenerates scripts/jungle-backdrop.mjs (the icon backdrop) from the game's own foliage graphics: `npm run jungle`.
// Then run `npm run icons` to rebuild the PNGs.
import { writeFileSync } from "node:fs";
import { BACKGROUNDS } from "../src/data/backgrounds";

const SIZE = 128;

// [background graphic index (see src/data/backgrounds.ts), x, y] - drawn in order, so later entries are in front.
// Black paper is transparent, so stamps can overlap and may hang over the edges (x/y can be negative).
const STAMPS: [number, number, number][] = [
  // top corners
  [8, -8, -2],
  [8, 112, -2],
  // tall vines on the left and right, reaching in to the medallion
  [10, -10, 20],
  [10, 106, 20],
  // top: two different bushes side by side, tucked behind the medallion
  [3, 0, -4],
  [5, 64, -10],
  // bottom: a corner fern, then clumps placed edge to edge (the fern sits behind the pineapple clump)
  [7, 104, 96],
  [1, 0, 88],
  [35, 38, 72],
  [6, 84, 72],
];

// One digit per pixel: ZX colour index (bit0 blue, bit1 red, bit2 green), 0 = black / transparent.
const canvas = new Uint8Array(SIZE * SIZE);

for (const [index, x0, y0] of STAMPS) {
  const bg = BACKGROUNDS[index];
  for (let py = 0; py < bg.heightPixels; py++) {
    for (let px = 0; px < bg.widthBytes * 8; px++) {
      // ROM bytes are stored inverted (draw byte ^ 0xFF); set bits use the cell's ink, clear bits its paper
      const bit =
        ((bg.pixels[py * bg.widthBytes + (px >> 3)] ^ 0xff) >> (7 - (px & 7))) &
        1;
      const attr = bg.attrs1[(py >> 3) * bg.attrWidth + (px >> 3)];
      const colour = bit ? attr & 7 : (attr >> 3) & 7;
      const x = x0 + px;
      const y = y0 + py;
      if (colour && x >= 0 && x < SIZE && y >= 0 && y < SIZE)
        canvas[y * SIZE + x] = colour;
    }
  }
}

const rows: string[] = [];
for (let y = 0; y < SIZE; y++)
  rows.push(Array.from(canvas.subarray(y * SIZE, (y + 1) * SIZE)).join(""));

const out =
  "// GENERATED by scripts/make-jungle.ts (`npm run jungle`) - jungle backdrop for the app icons, built from the game's own foliage graphics.\n" +
  "// 128x128 pixels, one digit per pixel: ZX colour index (bit0 blue, bit1 red, bit2 green; 0 = black).\n" +
  `export const JUNGLE_SIZE = ${SIZE};\nexport const JUNGLE_ROWS = [\n` +
  rows.map((r) => `  "${r}",`).join("\n") +
  "\n];\n";
writeFileSync(new URL("./jungle-backdrop.mjs", import.meta.url), out);
console.log("wrote scripts/jungle-backdrop.mjs");
